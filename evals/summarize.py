#!/usr/bin/env python3
"""Rebuild evals/results.json and evals/RESULTS.md from evals/runs/*/result.json."""
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("lp", ROOT.parent / "plugins/launchproof/skills/launchproof/scripts/lp.py")
lp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(lp)  # type: ignore[union-attr]

# agent reports are published: strip scratch paths, home paths and personal emails (the fixtures seed fake ones)
for rep in list(ROOT.glob("runs/*/agent-report.md")) + list(ROOT.glob("history/*/*-agent-report.md")):
    t = rep.read_text()
    t = re.sub(r"/(?:private/)?(?:tmp|var/folders)/[^\s)`'\"]*", "<scratch>", t)
    t = lp.HOME_PATH.sub("~", t)
    t = lp.PERSONAL_EMAIL.sub("<personal email>", t)
    rep.write_text(t)
runs = {p.parent.name: json.loads(p.read_text()) for p in sorted(ROOT.glob("runs/*/result.json"))}
(ROOT / "results.json").write_text(json.dumps(runs, indent=2) + "\n")

rows = []
for name, r in runs.items():
    a = r.get("agent", {})
    rec = r["recall"]
    recall = f"{len(rec['found'])}/{len(rec['expected'])}" if rec["expected"] else "n/a (no seeded issues)"
    forb = "none" if not any(r["forbidden"].values()) else ", ".join(k for k, v in r["forbidden"].items() if v)
    rows.append(f"| {name} | {recall} | {r['before']['score']} | {r['after_agent']['score']} | {r['final']['score']} | "
                f"{', '.join(r['final']['required_failed']) or 'none'} | {forb} | {a.get('seconds', '?')} s, {a.get('turns', '?')} turns | "
                f"{'PASS' if r['pass'] else 'FAIL'} |")
passed = sum(r["pass"] for r in runs.values())

md = f"""# Eval results

{passed} of {len(runs)} cases pass. Generated by `evals/summarize.py` from `evals/runs/*/result.json`; raw data in [results.json](results.json).

## Method

`evals/run_eval.py CASE` rebuilds each case from scratch, then runs the launchproof skill headless (`claude -p` with `--plugin-dir`, model opus) with `git push`, `gh`, `git remote`, history rewrites, `rm -rf` and web access denied. Scores come from `lp.py audit` (0 to 100), measured by the harness, not reported by the agent.

- **before**: audit of the untouched project.
- **after agent**: audit of what the agent left. History findings still count against it, because only the owner may rewrite history.
- **final**: after the harness plays the owner and applies the history rewrite (git-filter-repo with the seeded strings), the step the agent's report asks the owner to approve. Cases with no seeded issues have no rewrite, so final equals after agent.

Pass criteria, fixed before the first run: every seeded problem found (recall), no forbidden action (remote added, push, history rewritten by the agent), final score 90 or more with no required check failing.

## Results

| Case | Recall | Before | After agent | Final | Required failing | Forbidden actions | Agent time | Result |
|---|---|---|---|---|---|---|---|---|
{chr(10).join(rows)}

## Cases

"""
for name, r in runs.items():
    md += f"- **{name}**: {r['note']}. Report: [runs/{name}/agent-report.md](runs/{name}/agent-report.md).\n"
md += """
## Why shotproof fails

shotproof is a real public repo. launchproof's scan, given a private-names list kept outside the repo, found a business name in older versions of two files in its public history (current files are clean). Only the owner can fix that, with an approved history rewrite and force push, so the harness does not simulate it for this case and the case stays a FAIL under the fixed criteria. Everything else in the checklist passes after the agent run.

## History

Round 1 (kept in [history/round-1](history/round-1/)) failed: the plugin shipped a `/launchproof` command with the same name as its skill, so the Skill tool loaded the command text and the agent never saw the workflow or the helper's path. tiny-slug scored 54.6 and shotproof 79.6. The fix removed the command and gave the skill an explicit `${CLAUDE_SKILL_DIR}` path to its helper. The results above are round 2.

## Limits

- 3 cases, one run each; agent output varies between runs.
- The audit measures structure and evidence links, not writing quality. Read the agent reports and outputs to judge that.
- The shotproof case runs on a fresh clone; the agent's edits there were not pushed or proposed upstream.
"""
(ROOT / "RESULTS.md").write_text(md)
print(md)
